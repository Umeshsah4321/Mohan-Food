const DEFAULT_FOOD_IMAGE = "https://images.unsplash.com/photo-1504674900247-0877df9cc836?w=800&q=80";

/**
 * Returns the correct food image for a food item.
 * Priority: name map → category map → image_url from DB → default
 */
export function getFoodImageByName(food) {
  if (!food) return DEFAULT_FOOD_IMAGE;

  // 1. Try exact name match from our curated map
  const nameKey = (food.name || "").toLowerCase().trim();
  if (FOOD_IMAGE_MAP[nameKey]) return FOOD_IMAGE_MAP[nameKey];

  // 2. Try partial name match (e.g. "Special Biryani" → biryani key)
  for (const [key, url] of Object.entries(FOOD_IMAGE_MAP)) {
    if (nameKey.includes(key) || key.includes(nameKey)) return url;
  }

  // 3. Try category fallback
  const catKey = (food.category?.name || food.category_name || "").toLowerCase().trim();
  if (CATEGORY_IMAGE_MAP[catKey]) return CATEGORY_IMAGE_MAP[catKey];

  return DEFAULT_FOOD_IMAGE;
}

/**
 * Returns the correct category image.
 */
export function getCategoryImageByName(cat) {
  if (!cat) return DEFAULT_FOOD_IMAGE;
  const key = (cat.name || "").toLowerCase().trim();
  return CATEGORY_IMAGE_MAP[key] || DEFAULT_FOOD_IMAGE;
}
